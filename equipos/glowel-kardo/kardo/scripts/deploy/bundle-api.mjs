// Bundles one Node API (customer-api or staff-api) into a self-contained
// Cloud Run build context: services/<name>/.deploy/{index.mjs,Dockerfile}.
// Workspace packages ship as TypeScript sources, so production needs a
// bundle; every npm dependency is inlined too, which keeps the image to a
// single file on top of the official Node image (no install step, no
// monorepo, no .env in the build context).
// Usage: node scripts/deploy/bundle-api.mjs customer-api|staff-api
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const service = process.argv[2];
if (!["customer-api", "staff-api"].includes(service)) {
  throw new Error("Usage: bundle-api.mjs customer-api|staff-api");
}
const serviceDir = path.join(root, "services", service);
const outDir = path.join(serviceDir, ".deploy");
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const nodeVersion = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8")).engines.node;

const result = await build({
  entryPoints: [path.join(serviceDir, "src/index.ts")],
  outfile: path.join(outDir, "index.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: `node${nodeVersion.split(".")[0]}`,
  sourcemap: false,
  minify: false,
  legalComments: "none",
  metafile: true,
  // CommonJS dependencies inside an ESM bundle still call require() and use
  // __dirname; provide both.
  banner: {
    js: [
      'import { createRequire as __kardoCreateRequire } from "node:module";',
      'import { fileURLToPath as __kardoFileURLToPath } from "node:url";',
      'import { dirname as __kardoDirname } from "node:path";',
      "const require = __kardoCreateRequire(import.meta.url);",
      "const __filename = __kardoFileURLToPath(import.meta.url);",
      "const __dirname = __kardoDirname(__filename);",
    ].join("\n"),
  },
  logLevel: "warning",
});

fs.writeFileSync(
  path.join(outDir, "Dockerfile"),
  `# Generated by scripts/deploy/bundle-api.mjs — do not edit.
FROM node:${nodeVersion}-slim
ENV NODE_ENV=production
WORKDIR /app
COPY index.mjs ./index.mjs
USER node
EXPOSE 8080
CMD ["node", "index.mjs"]
`,
);
fs.writeFileSync(path.join(outDir, ".dockerignore"), "*\n!index.mjs\n");
fs.writeFileSync(path.join(outDir, ".gcloudignore"), "*\n!index.mjs\n!Dockerfile\n");

const bytes = fs.statSync(path.join(outDir, "index.mjs")).size;
const inputs = Object.keys(result.metafile.inputs).length;
console.log(`${service}: ${(bytes / 1024).toFixed(0)} KiB, ${inputs} módulos → ${path.relative(root, outDir)}/`);
