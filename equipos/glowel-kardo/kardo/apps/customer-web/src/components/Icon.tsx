export type IconName = keyof typeof icons;

export function Icon({
  name,
  size = 18,
  className,
}: {
  name: IconName;
  size?: number | undefined;
  className?: string | undefined;
}) {
  const Component = icons[name];
  return (
    <Component
      aria-hidden="true"
      className={className ? `icon ${className}` : "icon"}
      focusable="false"
      size={size}
      strokeWidth={1.7}
    />
  );
}
