export type City = {
  name: string;
  state: string;
  /** What the profile keeps: «Toluca, Estado de México»; a capital that
   * shares its state's name is just «Puebla». */
  value: string;
};

const fold = (text: string) =>
  foldText(text).replace(/[.,]/g, " ").replace(/\s+/g, " ").trim();

export const mxCities: City[] = Object.entries(states).flatMap(
  ([state, names]) =>
    names.map((name) => ({
      name,
      state,
      value: name === state ? name : `${name}, ${state}`,
    })),
);

const index = mxCities.map((city) => ({
  city,
  name: fold(city.name),
  words: fold(city.name).split(" "),
  full: fold(`${city.name} ${city.state}`),
}));

/**
 * Cities for what was typed, without minding accents or capitals: first
 * the ones whose name starts with it, then a word that starts with it,
 * then the rest that contain it (also by state: «cholula pue»).
 */
export function searchCities(query: string, limit = 8): City[] {
  const typed = fold(query);
  if (!typed) return [];
  const ranked: { city: City; rank: number }[] = [];
  for (const entry of index) {
    let rank = -1;
    if (entry.name.startsWith(typed)) rank = 0;
    else if (entry.words.some((word) => word.startsWith(typed))) rank = 1;
    else if (entry.full.includes(typed)) rank = 2;
    else if (typed.split(" ").every((part) => entry.full.includes(part)))
      rank = 3;
    if (rank >= 0) ranked.push({ city: entry.city, rank });
  }
  return ranked
    .sort(
      (a, b) => a.rank - b.rank || a.city.name.localeCompare(b.city.name, "es"),
    )
    .slice(0, limit)
    .map((entry) => entry.city);
}

/** True when the text is exactly one of the cities (as saved). */
export function isKnownCity(value: string): boolean {
  const typed = fold(value);
  return mxCities.some((city) => fold(city.value) === typed);
}
